'use strict';
const fs = require('fs');
const path = require('path');
const { createStore } = require('../../electron/store');
const { createService } = require('../../electron/service');
const { createPriceWatcher } = require('../../electron/price-watcher');
const RP = require('../../electron/repricer-engine');
let pass = 0, fail = 0;
function check(name, ok, detail) {
  if (ok) pass++; else fail++;
  console.log((ok ? 'OK   ' : 'FAIL ') + name + (detail ? ' — ' + detail : ''));
}
const dir = path.join(__dirname, '..', '..', '.data-test-pricewatch');
const fixture = (name) => fs.readFileSync(path.join(__dirname, 'fixtures', name), 'utf8');
const normal = fixture('price-watch-normal.json'), changed = fixture('price-watch-changed.json');
const calls = [];
let status = 200, body = normal, contentType = 'application/json';
global.fetch = async (url, init) => {
  calls.push({ url, init, time: Date.now() });
  return { status, ok: status >= 200 && status < 300, headers: { get: () => contentType }, text: async () => body };
};
async function run() {
  fs.rmSync(dir, { recursive: true, force: true });
  const store = createStore(dir);
  check('Автозапросы по умолчанию выключены', store.loadSettings().priceWatchAutoFetch === false);
  const w = createPriceWatcher({ store, minIntervalMs: 30 });
  let r = w.recordManual({ nmID: 1, shelfPrice: 1000, sppPrice: 850, source: 'manual', note: 'тест' });
  check('Ручная СПП', r.ok && r.sppPct === 15);
  r = w.recordManual({ nmID: 1, shelfPrice: 0, sppPrice: 0 });
  check('Защита от деления на ноль', r.ok && r.sppPct === null);
  r = await w.fetchFromSite({ nmID: 101 });
  check('Цена в копейках переведена в рубли', r.ok && r.basePrice === 1250 && r.shelfPrice === 1000 && r.sppPrice === 850 && r.sppPct === 15);
  check('Остаток, бренд, название и скидка', r.stock === 5 && r.brand === 'Бренд' && r.title === 'Товар' && r.sellerDiscountPct === 20);
  const before = calls.length;
  r = await w.fetchFromSite({ nmID: 101 });
  check('Кэш предотвращает повторный запрос', r.fromCache === true && calls.length === before);
  body = changed;
  r = await w.fetchFromSite({ nmID: 102 });
  check('Другая схема', r.ok && r.basePrice === 2000 && r.shelfPrice === 1500 && r.sppPrice === 1200 && r.sppPct === 20 && r.stock === 5);
  store.saveCompetitors({ '1': [{ id: 'stable-id', sku: 102, name: 'Конкурент', price: 1, stock: 1, enabled: true }] });
  r = await w.fetchCompetitor({ competitorSKU: 102 });
  let c = store.loadCompetitors()['1'][0];
  check('Цена конкурента попадает в репрайсер и id сохранён', r.ok && c.id === 'stable-id' && c.price === 1200 && c.stock === 5 && RP.bestCompetitorPrice({ competitors: [c], sppPct: 0 }, {}).price === 1200);
  r = w.recordManual({ nmID: 1, competitorSKU: 102, competitorPrice: 1100, competitorStock: 0 });
  c = store.loadCompetitors()['1'][0];
  check('Ручной ввод конкурента и нулевой остаток', r.ok && c.price === 1100 && c.stock === 0 && RP.bestCompetitorPrice({ competitors: [c] }, {}) === null);
  const timing = createPriceWatcher({ store, minIntervalMs: 60, ttlMinutes: 0 });
  body = normal; const startCalls = calls.length;
  r = await timing.runBatch({ nmIDs: [101, 101], competitorSKUs: [101], concurrency: 3 });
  const times = calls.slice(startCalls).map((v) => v.time);
  check('Пакет не нарушает общий интервал при concurrency > 1', r.ok && times.length === 2 && times[1] - times[0] >= 60, 'интервал ' + (times[1] - times[0]) + ' мс');
  check('План ограничен 200 товарами', w.planRefresh(Array.from({ length: 220 }, (_, i) => i + 1)).length === 200);
  r = await w.runBatch({ nmIDs: Array.from({ length: 201 }, (_, i) => i + 1) });
  check('Пакет более 200 отклонён до сети', r.code === 'LIMIT');
  status = 403;
  const blockedWatcher = createPriceWatcher({ store, minIntervalMs: 0 });
  const prior = calls.length;
  r = await blockedWatcher.runBatch({ nmIDs: [101, 102] });
  const again = await blockedWatcher.fetchFromSite({ nmID: 102, force: true });
  check('403: BLOCKED, русское сообщение, остановка без повтора', !r.ok && r.blocked === 1 && r.results[0].code === 'BLOCKED' && /вручную/.test(r.results[0].message) && again.code === 'BLOCKED' && calls.length === prior + 1);
  status = 429;
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchFromSite({ nmID: 101 });
  check('429 также означает BLOCKED', r.code === 'BLOCKED');
  status = 200; contentType = 'text/html'; body = '<html>captcha</html>';
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchFromSite({ nmID: 101 });
  check('HTML классифицируется как BLOCKED', r.code === 'BLOCKED');
  contentType = 'application/json'; body = '{"data":{"products":[{"id":102,"salePriceU":100000}]}}';
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchCompetitor({ competitorSKU: 102 });
  c = store.loadCompetitors()['1'][0];
  check('Неизвестные СПП и остаток не участвуют в репрайсере', r.ok && r.priceWithSpp === null && c.price === 0 && c.stock === null && RP.bestCompetitorPrice({ competitors: [c] }, {}) === null);
  body = '{"data":{"products":[{"id":101}]}}'; contentType = 'application/json';
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchFromSite({ nmID: 101 });
  check('Неизвестная схема не выдумывает цену', r.code === 'PARSE_FAILED');
  body = '{"data":{"products":[]}}';
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchFromSite({ nmID: 101 });
  check('Пустой список — NOT_FOUND', r.code === 'NOT_FOUND');
  global.fetch = async () => { throw new Error('offline'); };
  r = await createPriceWatcher({ store, minIntervalMs: 0 }).fetchFromSite({ nmID: 101 });
  check('Сетевая ошибка не выбрасывается наружу', r.code === 'NETWORK');
  for (let i = 0; i < 55; i++) w.recordManual({ nmID: 500, shelfPrice: 100, sppPrice: 90 });
  check('История ограничена 50', store.loadPriceWatch()['500'].length === 50);
  const now = new Date().toISOString(), old = new Date(Date.now() - 8 * 86400000).toISOString();
  store.appendPriceWatch([{ nmID: 501, at: now, sppPct: 10 }, { nmID: 501, at: now, sppPct: 20 }, { nmID: 501, at: now, sppPct: 40 }, { nmID: 501, at: old, sppPct: 99 }]);
  check('Медиана за 7 дней', w.sppForEconomics(501) === 20);
  store.appendPriceWatch([{ nmID: 502, at: now, sppPct: 0 }, { nmID: 502, at: now, sppPct: 10 }]);
  check('Медиана чётного набора учитывает ноль', w.sppForEconomics(502) === 5);
  check('Нет данных — null', w.sppForEconomics(999) === null);
  check('Без Electron возвращается NO_BROWSER', (await w.openInBrowser('https://www.wildberries.ru/catalog/101/detail.aspx')).code === 'NO_BROWSER');
  check('Посторонний URL запрещён', (await w.openInBrowser('http://127.0.0.1')).code === 'INVALID_URL');
  const svc = createService(store, () => {});
  r = await svc.handlers['pricewatch:fetch']({ nmIDs: [101] });
  check('IPC не запускает сеть без разрешения', r.code === 'AUTO_DISABLED');
  r = await svc.handlers['pricewatch:history']({ nmID: 501 });
  check('IPC истории и СПП', r.ok && r.sppPct === 20);
  r = await svc.handlers['pricewatch:record']({ nmID: 123, shelfPrice: 100, sppPrice: 80 });
  check('IPC ручного ввода', r.ok && r.sppPct === 20);
}
run().catch((e) => { fail++; console.error('FAIL непредвиденное исключение:', e.stack); }).finally(() => {
  fs.rmSync(dir, { recursive: true, force: true });
  console.log('\nВсего проверок: ' + (pass + fail) + ', успешно: ' + pass + ', ошибок: ' + fail);
  console.log('ИТОГ: ' + (fail ? 'ОШИБКА' : 'УСПЕХ'));
  process.exit(fail ? 1 : 0);
});
